import type { CategorySlug, Condition, Item, PickupSpotId, Rates, Review } from "./types";

/** Items under this retail value carry no deposit (customer research: only 4 of 12 wanted one). */
export const DEPOSIT_THRESHOLD = 100;

type Raw = {
  slug: string;
  brand: string;
  name: string;
  cat: CategorySlug;
  sub: string;
  retail: number;
  rates: Rates;
  /** Listed deposit; replaced with 0 under DEPOSIT_THRESHOLD. */
  deposit: number;
  condition: Condition;
  size?: string;
  description: string;
  included: string[];
  specs: [string, string][];
  lender: string;
  spots: PickupSpotId[];
  query: string;
  listed: string;
  blocked: string[];
  minDays?: number;
  tags: string[];
  reviews?: Review[];
};

function build(r: Raw): Item {
  const cleaned = r.cat === "formal" || r.cat === "costumes";
  return {
    slug: r.slug,
    name: r.name,
    brand: r.brand,
    categorySlug: r.cat,
    subcategory: r.sub,
    retailValue: r.retail,
    rates: r.rates,
    deposit: r.retail < DEPOSIT_THRESHOLD ? 0 : r.deposit,
    condition: r.condition,
    size: r.size,
    description: r.description,
    whatsIncluded: r.included,
    specs: r.specs.map(([label, value]) => ({ label, value })),
    lenderId: r.lender,
    pickupSpotIds: r.spots,
    images: [`/items/${r.slug}/1.jpg`, `/items/${r.slug}/2.jpg`],
    imageQuery: r.query,
    listedAt: r.listed,
    blockedDates: r.blocked,
    minDays: r.minDays,
    tags: r.tags,
    cleanedBetweenRentals: cleaned || undefined,
    reviews: r.reviews ?? [],
  };
}

